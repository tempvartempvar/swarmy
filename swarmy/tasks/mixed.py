"""Mixed research + coding: implement a pricing function whose parameters are only
documented in the knowledge base. Agents must find the facts, then encode them."""

from __future__ import annotations

import random
from pathlib import Path

from .base import Grade, TaskInstance, run_cases
from .code import summarize_cases
from .world import LOYALTY_LEVELS, generate_world

RULES = ["bulk", "loyalty", "shipping", "surcharge", "tax"]
TOL = 0.011


class MixedTask(TaskInstance):
    family = "mixed"

    def __init__(self, params: dict, seed: int):
        super().__init__(params, seed)
        n_products = int(params.get("products", 5))
        n_cities = int(params.get("cities", 4))
        n_rules = int(params.get("rules", 5))
        rules = RULES[: max(0, min(5, n_rules))]
        if "surcharge" in rules and "shipping" not in rules:
            rules.remove("surcharge")
        self.rules = rules
        world = generate_world(seed, scale=float(params.get("scale", 1.0)))
        self.world = world
        self.corpus = world.corpus
        rng = random.Random(f"mixed-{seed}-{n_products}-{n_cities}-{n_rules}")
        self.products = rng.sample(sorted(world.products), k=min(n_products, len(world.products)))
        self.cities = rng.sample(sorted(world.cities), k=min(n_cities, len(world.cities)))
        self.ref_source = self._reference_source()
        ns: dict = {}
        exec(self.ref_source, ns)  # trusted: generated by us
        self._quote = ns["quote"]
        self.public_cases = self._cases(random.Random(f"pub-{seed}"), 2)
        self.hidden_cases = self._cases(random.Random(f"hid-{seed}-{n_products}-{n_cities}"), 24)
        self.key_terms = self.products + self.cities
        spec = self._spec()
        self.workspace_files = {
            "SPEC.md": spec,
            "pricing.py": "# Implement quote(order) as described in SPEC.md.\n\n\ndef quote(order):\n    raise NotImplementedError\n",
        }
        self.title = "Implement order pricing from documented policy"
        self.brief = (
            f"{spec}\n\n"
            f"Resources: the policy facts (product prices and categories, bulk discounts, loyalty discounts, shipping "
            f"rates, surcharges, tax rates, which country each city is in) are spread across a knowledge base of "
            f"{len(self.corpus)} documents, together with unrelated documents. Hands-on roles can search it "
            f"(search_docs, read_doc), read/write workspace files and run Python. `run_tests` checks the two public "
            f"examples. Hidden tests price many orders; the score is the fraction priced correctly (within one cent)."
        )

    def _spec(self) -> str:
        steps = ["subtotal = (list price of the product) x quantity"]
        if "bulk" in self.rules:
            steps.append("if quantity >= the bulk-order threshold for the product's category, reduce subtotal by "
                         "that category's bulk discount percentage (subtotal = subtotal x (1 - pct/100))")
        if "loyalty" in self.rules:
            steps.append("reduce subtotal by the customer's loyalty discount percentage "
                         "(subtotal = subtotal x (1 - pct/100))")
        if "shipping" in self.rules:
            steps.append("shipping = base shipping fee + per-kilogram fee x weight_kg, using the rates of the "
                         "country the destination city is in")
        else:
            steps.append("shipping = 0")
        if "surcharge" in self.rules:
            steps.append("increase shipping by the destination city's congestion surcharge percentage "
                         "(shipping = shipping x (1 + pct/100))")
        if "tax" in self.rules:
            steps.append("tax = subtotal x (VAT rate of the destination city's country) / 100")
        else:
            steps.append("tax = 0")
        steps.append("total = round(subtotal + shipping + tax, 2)  (Python's round); return it as a float")
        numbered = "\n".join(f"{i + 1}. {s}" for i, s in enumerate(steps))
        ex = "\n".join(f"- quote({c['args'][0]!r}) -> {c['expected']}" for c in self.public_cases)
        return (
            "# Order pricing\n\n"
            "Implement `quote(order)` in `pricing.py` (a stub is provided). An order is a dict like\n"
            "`{\"product\": <name>, \"quantity\": <int>, \"city\": <destination city>, \"weight_kg\": <float>, "
            "\"member\": <loyalty level>}`.\n\n"
            f"quote must support these products: {', '.join(self.products)}.\n"
            f"Destination cities: {', '.join(self.cities)}.\n"
            f"Loyalty levels: {', '.join(LOYALTY_LEVELS)}.\n\n"
            f"Compute the total exactly like this:\n{numbered}\n\n"
            "The function must be self-contained (hard-code the facts you find). Use only the standard library.\n\n"
            f"Public examples:\n{ex}\n"
        )

    def _reference_source(self) -> str:
        w = self.world
        prices = {p: w.products[p].price for p in self.products}
        cats = {p: w.products[p].category for p in self.products}
        bulk = {c: (w.categories[c].bulk_threshold, w.categories[c].bulk_discount_pct) for c in set(cats.values())}
        city_country = {c: w.cities[c].country for c in self.cities}
        ship = {k: (w.countries[k].ship_base, w.countries[k].ship_per_kg) for k in set(city_country.values())}
        surcharge = {c: w.cities[c].surcharge_pct for c in self.cities}
        vat = {k: w.countries[k].vat_pct for k in set(city_country.values())}
        r = self.rules
        lines = [
            f"PRICES = {prices!r}", f"CATEGORY = {cats!r}", f"BULK = {dict(sorted(bulk.items()))!r}",
            f"LOYALTY = {w.loyalty_pct!r}", f"CITY_COUNTRY = {city_country!r}",
            f"SHIP = {dict(sorted(ship.items()))!r}", f"SURCHARGE = {surcharge!r}", f"VAT = {dict(sorted(vat.items()))!r}",
            "", "", "def quote(order):",
            "    product, qty, city = order['product'], order['quantity'], order['city']",
            "    country = CITY_COUNTRY[city]",
            "    subtotal = PRICES[product] * qty",
        ]
        if "bulk" in r:
            lines += ["    threshold, pct = BULK[CATEGORY[product]]",
                      "    if qty >= threshold:", "        subtotal = subtotal * (1 - pct / 100)"]
        if "loyalty" in r:
            lines += ["    subtotal = subtotal * (1 - LOYALTY[order['member']] / 100)"]
        if "shipping" in r:
            lines += ["    base, per_kg = SHIP[country]", "    shipping = base + per_kg * order['weight_kg']"]
        else:
            lines += ["    shipping = 0.0"]
        if "surcharge" in r:
            lines += ["    shipping = shipping * (1 + SURCHARGE[city] / 100)"]
        lines += ["    tax = subtotal * VAT[country] / 100" if "tax" in r else "    tax = 0.0",
                  "    return round(subtotal + shipping + tax, 2)", ""]
        return "\n".join(lines)

    def _cases(self, rng: random.Random, n: int) -> list[dict]:
        cases = []
        for _ in range(n):
            order = {
                "product": rng.choice(self.products),
                "quantity": rng.randint(1, 15),
                "city": rng.choice(self.cities),
                "weight_kg": rng.randint(1, 40) / 2,
                "member": rng.choice(LOYALTY_LEVELS),
            }
            cases.append({"module": "pricing", "func": "quote", "args": [order],
                          "expected": self._quote(order), "tol": TOL})
        return cases

    def reference_files(self) -> dict[str, str]:
        return {"pricing.py": self.ref_source}

    @property
    def has_public_tests(self) -> bool:
        return True

    def public_tests(self, workspace: Path) -> str:
        return summarize_cases(self.public_cases, run_cases(workspace, self.public_cases))

    def _score(self, workspace: Path) -> float:
        results = run_cases(workspace, self.hidden_cases)
        return sum(bool(r.get("ok")) for r in results) / max(1, len(results))

    def grade(self, answer: str | None, workspace: Path) -> Grade:
        frac = self._score(workspace)
        return Grade(score=frac, passed=frac == 1.0, details={"hidden_passed": f"{round(frac * len(self.hidden_cases))}/{len(self.hidden_cases)}"})

    def progress(self, workspace: Path) -> float | None:
        return self._score(workspace)

    def gold(self) -> dict:
        return {"rules": self.rules, "reference": self.ref_source}
